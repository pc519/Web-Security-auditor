import requests
import ssl
import socket
from datetime import datetime
from urllib.parse import urlparse

def get_ssl_expiry(hostname):
    try:
        context = ssl.create_default_context()
        with socket.create_connection((hostname, 443), timeout=5) as sock:
            with context.wrap_socket(sock, server_hostname=hostname) as ssock:
                cert = ssock.getpeercert()
                expiry_str = cert['notAfter']
                expiry_date = datetime.strptime(expiry_str, '%b %d %H:%M:%S %Y %Z')
                days_left = (expiry_date - datetime.utcnow()).days
                return f"Valid ({days_left} days remaining)"
    except Exception:
        return "Could not verify SSL or No HTTPS"

def audit_website(url):
    if not url.startswith(("http://", "https://")):
        url = "https://" + url

    parsed_url = urlparse(url)
    hostname = parsed_url.netloc

    print(f"\n[+] Starting Security Audit for: {url}")
    print("=" * 60)

    try:
        response = requests.get(url, timeout=10)
        headers = response.headers
        ssl_status = get_ssl_expiry(hostname)
        print(f"[*] SSL Certificate Status: {ssl_status}")
        print("-" * 60)

        security_headers = {
            "Strict-Transport-Security": "Enforces secure HTTPS connections (HSTS)",
            "X-Frame-Options": "Protects against Clickjacking attacks",
            "X-Content-Type-Options": "Prevents MIME-sniffing vulnerabilities",
            "Content-Security-Policy": "Mitigates Cross-Site Scripting (XSS) attacks",
            "Referrer-Policy": "Controls how much referrer info is shared"
        }

        score = 0
        results_html = ""

        for header, desc in security_headers.items():
            if header in headers:
                print(f"[PASS] {header} -> Present")
                score += 20
                results_html += f"<tr style='background:#e8f5e9;'><td><b>{header}</b></td><td style='color:green;'>PASS</td><td>{desc}</td></tr>"
            else:
                print(f"[FAIL] {header} -> Missing ({desc})")
                results_html += f"<tr style='background:#ffebee;'><td><b>{header}</b></td><td style='color:red;'>MISSING</td><td>{desc}</td></tr>"

        print("=" * 60)
        print(f"[*] Final Security Score: {score}/100")

        # توليد تقرير HTML احترافي جاهز للعميل
        report_filename = f"report_{hostname.replace('.', '_')}.html"
        html_content = f"""
        <html>
        <head><title>Security Audit Report - {hostname}</title></head>
        <body style="font-family: Arial, sans-serif; margin: 40px; background-color: #f4f6f9;">
            <div style="max-width: 800px; margin: auto; background: white; padding: 30px; border-radius: 10px; box-shadow: 0 0 10px rgba(0,0,0,0.1);">
                <h1 style="color: #2c3e50;">Web Security Audit Report</h1>
                <p><b>Target Website:</b> {url}</p>
                <p><b>SSL Status:</b> {ssl_status}</p>
                <h2 style="color: #2980b9;">Security Score: {score}/100</h2>
                <table border="1" cellpadding="10" cellspacing="0" style="width: 100%; border-collapse: collapse;">
                    <tr style="background: #2c3e50; color: white;">
                        <th>Security Header</th>
                        <th>Status</th>
                        <th>Description & Impact</th>
                    </tr>
                    {results_html}
                </table>
                <p style="margin-top: 20px; font-size: 12px; color: gray;">Generated by Custom Python Security Auditor</p>
            </div>
        </body>
        </html>
        """
        with open(report_filename, "w", encoding="utf-8") as f:
            f.write(html_content)

        print(f"[+] Professional HTML Report saved as: {report_filename}")

    except Exception as e:
        print(f"[!] Error auditing website: {e}")

if __name__ == "__main__":
    target = input("Enter target domain (e.g., example.com): ").strip()
    if target:
        audit_website(target)